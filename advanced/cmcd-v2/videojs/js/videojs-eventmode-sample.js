// VideoJS CMCD v2 Event Mode Sample
let player;
let cmcdSessionId = null;
let contentUri = dashUri; // Default to DASH, will be updated based on DRM type
let isLicenseRequestPending = false;
let pendingLicenseDataToSend = false;
let drmLicenseMetrics = {
    requestTimestamp: null,
    responseTimestamp: null,
    requestCount: 0,
    latencies: [],
    errorCodes: [],
    serverResponseCodes: []
};

function init() {
    updateCmcdUrlDisplay('cmcd-reporting-url');

    checkSupportedDRM().then(() => {
        setupPlayer();
        checkBrowser();
    });

    function setupPlayer() {
        // Initialize VideoJS player
        player = videojs('my-player');

        log('VideoJS version: ' + (videojs.VERSION || 'unknown'));

        // Configure CMCD v2 plugin (session ID will be auto-generated by plugin)
        player.cmcd({
            version: 2,
            targets: [
                {
                    mode: 'event',
                    url: CMCD_REPORTING_SERVER_URL,
                    transmissionMode: 'json',  // Use JSON for batch transmission
                    batchSize: 100,            // Send batch when 100 events accumulated
                    batchTimer: 30,            // Also send batch every 30 seconds
                    timeInterval: 10,          // Add periodic time interval event every 10 seconds

                    beforeSend: function(cmcdBatch) {
                        // Add custom data to batch before sending
                        addCustomDataToCmcdBatch(cmcdBatch);
                    }
                }
            ]
        });

        // Capture the session ID generated by the plugin using the new getter method
        setTimeout(function() {
            try {
                // Call player.cmcd() without arguments to get the plugin instance
                const cmcdPlugin = player.cmcd();
                if (cmcdPlugin && typeof cmcdPlugin.getSessionId === 'function') {
                    cmcdSessionId = cmcdPlugin.getSessionId();
                    log('CMCD Session ID captured from VideoJS plugin: ' + cmcdSessionId);
                } else {
                    log('Warning: CMCD plugin getSessionId method not available');
                }
            } catch (e) {
                log('Warning: Could not access CMCD plugin: ' + e.message);
            }
        }, 100);

        if (activeDrm.type !== 'No DRM') {
            setupDRM();
            setupLicenseFilters();
        }

        // Setup player event listeners
        setupPlayerEventListeners();

        // Video source will be set in setupDRM function

        log('VideoJS player initialized with CMCD v2 Event Mode');
    }

    function setupPlayerEventListeners() {
        // Standard player events for logging
        player.on('play', function() {
            log('Player started playing');
        });

        player.on('pause', function() {
            log('Player paused');
        });

        player.on('ended', function() {
            log('Playback ended');
        });

        player.on('error', function(event) {
            const error = player.error();
            if (error) {
                log('Player error occurred: ' + error.message + ' (Code: ' + error.code + ')');
            }
        });

        player.on('loadstart', function() {
            log('Load started');
        });

        player.on('canplay', function() {
            log('Can start playing');
        });

        player.on('volumechange', function() {
            if (player.muted()) {
                log('Player muted');
            } else {
                log('Player unmuted - volume: ' + Math.round(player.volume() * 100) + '%');
            }
        });
    }

    function addCustomDataToCmcdBatch(cmcdBatch) {
        try {
            if (!Array.isArray(cmcdBatch) || cmcdBatch.length === 0) {
                log('No CMCD batch to modify');
                return;
            }

            log('Adding custom data to CMCD batch (' + cmcdBatch.length + ' events)');

            // Prepare base custom data (common for all events)
            const baseCustomData = {
                'sid': cmcdSessionId,
                'com.doverunner.device-id': getDeviceId(),
                'com.doverunner.player.device-type': getDeviceType(),
                'com.doverunner.player.browser-type': getBrowserName() + '-' + getBrowserVersion(),
                'com.doverunner.drm-auth-data': getDrmAuthData()
            };

            // Check if first event already has license data (from previous failed transmission)
            const firstEventHasLicenseData = cmcdBatch[0]['com.doverunner.drm-license-requested-count'] !== undefined &&
                cmcdBatch[0]['com.doverunner.drm-license-requested-count'] > 0;

            // Prepare license data (only for first event in batch)
            let licenseDataToAdd = null;
            const currentRequestCount = drmLicenseMetrics.requestCount;

            if (currentRequestCount > 0 && !firstEventHasLicenseData) {
                log('Preparing license metrics for first event: requestCount=' + currentRequestCount);

                while (drmLicenseMetrics.errorCodes.length < currentRequestCount) {
                    drmLicenseMetrics.latencies.push(-1);
                    drmLicenseMetrics.errorCodes.push(-1);
                    drmLicenseMetrics.serverResponseCodes.push(-1);
                }

                licenseDataToAdd = {
                    'com.doverunner.drm-license-requested-count': currentRequestCount
                };

                for (let i = 0; i < drmLicenseMetrics.latencies.length; i++) {
                    const requestNum = i + 1;
                    licenseDataToAdd['com.doverunner.drm-license-latency-' + requestNum] = drmLicenseMetrics.latencies[i].toFixed(2);
                    licenseDataToAdd['com.doverunner.drm-error-code-' + requestNum] = drmLicenseMetrics.errorCodes[i];
                    licenseDataToAdd['com.doverunner.drm-server-response-code-' + requestNum] = drmLicenseMetrics.serverResponseCodes[i];
                }
            } else if (firstEventHasLicenseData) {
                log('First event already has license data (retry transmission), skipping addition');
            }

            // Add custom data to each event in the batch
            cmcdBatch.forEach((cmcdObj, index) => {
                if (cmcdObj && typeof cmcdObj === 'object') {
                    // Add base custom data to all events
                    Object.assign(cmcdObj, baseCustomData);

                    // ONLY the first event gets license data
                    if (index === 0 && licenseDataToAdd) {
                        Object.assign(cmcdObj, licenseDataToAdd);
                        log('License data (count=' + currentRequestCount + ' + details) added to first event (index 0)');
                    } else if (!cmcdObj['com.doverunner.drm-license-requested-count']) {
                        // All other events (including first event if no license data) get count = 0 (if not already set)
                        cmcdObj['com.doverunner.drm-license-requested-count'] = 0;
                    }
                }
            });

            // Reset DRM metrics immediately after adding to batch (before transmission)
            if (licenseDataToAdd) {
                resetDrmMetrics();
                log('DRM metrics reset immediately after adding to batch (requestCount now 0)');
            }

            log('First event: ' + JSON.stringify(cmcdBatch[0]));
            if (cmcdBatch.length > 1) {
                log('Second event (should not have license details): ' + JSON.stringify(cmcdBatch[1]));
            }
        } catch (e) {
            log('Error adding custom data to CMCD batch: ' + e);
            console.error('Error details:', e);
        }
    }

    function resetDrmMetrics() {
        drmLicenseMetrics = {
            requestTimestamp: null,
            responseTimestamp: null,
            requestCount: 0,
            latencies: [],
            errorCodes: [],
            serverResponseCodes: []
        };
    }

    function setupDRM() {
        // DRM setup for VideoJS using the same approach as the main sample
        player.ready(function() {
            let playerConfig;

            // Check if EME plugin is available
            if (typeof player.eme !== 'function') {
                log('VideoJS EME plugin not available - DRM functionality disabled');
                // Fallback to clear content
                player.src({
                    src: contentUri,
                    type: getVideoMimeType(contentUri)
                });
                return;
            }

            player.eme();

            if ('FairPlay' === activeDrm.type) {
                playerConfig = {
                    src: hlsUri,
                    type: 'application/x-mpegurl',
                    keySystems: {
                        [activeDrm.keySystem]: {
                            getCertificate: function (emeOptions, callback) {
                                videojs.xhr({
                                    url: fairplayCertUri,
                                    method: 'GET',
                                }, function (err, response, responseBody) {
                                    if (err) {
                                        callback(err);
                                        return;
                                    }
                                    callback(null, base64DecodeUint8Array(responseBody));
                                });
                            },
                            getContentId: function (emeOptions, initData) {
                                const contentId = arrayToString(initData);
                                return contentId.substring(contentId.indexOf('skd://') + 6);
                            },
                            getLicense: function (emeOptions, contentId, keyMessage, callback) {
                                isLicenseRequestPending = true;
                                drmLicenseMetrics.requestTimestamp = Date.now();
                                drmLicenseMetrics.requestCount++;

                                const headers = {
                                    'Content-type': 'application/x-www-form-urlencoded',
                                    'pallycon-customdata-v2': fairplayToken
                                };

                                // Add CMCD Session ID to license request header if available
                                if (cmcdSessionId) {
                                    headers['CMCD-Session'] = 'sid="' + cmcdSessionId + '"';
                                    log('CMCD Session ID added to FairPlay license request: ' + cmcdSessionId);
                                }

                                videojs.xhr({
                                    url: licenseUri,
                                    method: 'POST',
                                    responseType: 'text',
                                    body: 'spc=' + base64EncodeUint8Array(keyMessage),
                                    headers: headers
                                }, function (err, response, responseBody) {
                                    isLicenseRequestPending = false;
                                    drmLicenseMetrics.responseTimestamp = Date.now();
                                    const latency = drmLicenseMetrics.responseTimestamp - drmLicenseMetrics.requestTimestamp;

                                    if (err) {
                                        drmLicenseMetrics.errorCodes.push(err.code || -1);
                                        drmLicenseMetrics.serverResponseCodes.push(response ? response.statusCode : -1);
                                        drmLicenseMetrics.latencies.push(-1);
                                        log('FairPlay license error: ' + JSON.stringify(err));
                                        pendingLicenseDataToSend = true;
                                        callback(err);
                                        return;
                                    }

                                    drmLicenseMetrics.errorCodes.push(0);
                                    drmLicenseMetrics.serverResponseCodes.push(response.statusCode);
                                    drmLicenseMetrics.latencies.push(latency);
                                    log('FairPlay license acquired - latency: ' + latency + 'ms');
                                    pendingLicenseDataToSend = true;

                                    callback(null, base64DecodeUint8Array(responseBody));
                                });
                            }
                        }
                    }
                };
                contentUri = hlsUri;
            } else if ('PlayReady' === activeDrm.type) {
                playerConfig = {
                    src: dashUri,
                    type: 'application/dash+xml',
                    keySystems: {
                        [activeDrm.keySystem]: {
                            url: licenseUri,
                            getLicense: function(emeOptions, keyMessage, callback) {
                                isLicenseRequestPending = true;
                                drmLicenseMetrics.requestTimestamp = Date.now();
                                drmLicenseMetrics.requestCount++;

                                const headers = {
                                    'Content-Type': 'text/xml; charset=utf-8',
                                    'pallycon-customdata-v2': playreadyToken
                                };

                                // Add CMCD Session ID to license request header if available
                                if (cmcdSessionId) {
                                    headers['CMCD-Session'] = 'sid="' + cmcdSessionId + '"';
                                    log('CMCD Session ID added to PlayReady license request: ' + cmcdSessionId);
                                }

                                // In the getLicense callback, the entire PlayReadyKeyMessage data is passed to keyMessage, so only the Challenge payload should be parsed and requested.
                                const modifiedMessage = extractChallengeOnly(keyMessage);                            
                                const decodedMessage = atob(modifiedMessage);
                                const uint8Array = new Uint8Array(decodedMessage.length);
                                for (let i = 0; i < decodedMessage.length; i++) {
                                    uint8Array[i] = decodedMessage.charCodeAt(i);
                                }                            

                                videojs.xhr({
                                    url: licenseUri,
                                    method: 'POST',
                                    responseType: 'arraybuffer',
                                    body: uint8Array,
                                    headers: headers
                                }, function (err, response, responseBody) {
                                    isLicenseRequestPending = false;
                                    drmLicenseMetrics.responseTimestamp = Date.now();
                                    const latency = drmLicenseMetrics.responseTimestamp - drmLicenseMetrics.requestTimestamp;

                                    if (err) {
                                        drmLicenseMetrics.errorCodes.push(err.code || -1);
                                        drmLicenseMetrics.serverResponseCodes.push(response ? response.statusCode : -1);
                                        drmLicenseMetrics.latencies.push(-1);
                                        log('PlayReady license error: ' + JSON.stringify(err));
                                        pendingLicenseDataToSend = true;
                                        callback(err);
                                        return;
                                    }

                                    drmLicenseMetrics.errorCodes.push(0);
                                    drmLicenseMetrics.serverResponseCodes.push(response.statusCode);
                                    drmLicenseMetrics.latencies.push(latency);
                                    log('PlayReady license acquired - latency: ' + latency + 'ms');
                                    pendingLicenseDataToSend = true;

                                    callback(null, responseBody);
                                });
                            }
                        }
                    }
                };
                contentUri = dashUri;
            } else if ('Widevine' === activeDrm.type) {
                playerConfig = {
                    src: dashUri,
                    type: 'application/dash+xml',
                    keySystems: {
                        [activeDrm.keySystem]: {
                            getCertificate: function (emeOptions, callback) {
                                videojs.xhr({
                                    url: widevineCertUri,
                                    method: 'GET',
                                    responseType: 'arraybuffer',
                                }, function (err, response, responseBody) {
                                    if (err) {
                                        callback(err);
                                        return;
                                    }
                                    callback(null, responseBody);
                                });
                            },
                            url: licenseUri,
                            licenseHeaders: {
                                'pallycon-customdata-v2': widevineToken
                            },
                            persistentState: 'required',
                            getLicense: function(emeOptions, keyMessage, callback) {
                                isLicenseRequestPending = true;
                                drmLicenseMetrics.requestTimestamp = Date.now();
                                drmLicenseMetrics.requestCount++;

                                const headers = {
                                    'Content-Type': 'application/octet-stream',
                                    'pallycon-customdata-v2': widevineToken
                                };

                                // Add CMCD Session ID to license request header if available
                                if (cmcdSessionId) {
                                    headers['CMCD-Session'] = 'sid="' + cmcdSessionId + '"';
                                    log('CMCD Session ID added to Widevine license request: ' + cmcdSessionId);
                                }

                                videojs.xhr({
                                    url: licenseUri,
                                    method: 'POST',
                                    responseType: 'arraybuffer',
                                    body: keyMessage,
                                    headers: headers
                                }, function (err, response, responseBody) {
                                    isLicenseRequestPending = false;
                                    drmLicenseMetrics.responseTimestamp = Date.now();
                                    const latency = drmLicenseMetrics.responseTimestamp - drmLicenseMetrics.requestTimestamp;

                                    if (err) {
                                        drmLicenseMetrics.errorCodes.push(err.code || -1);
                                        drmLicenseMetrics.serverResponseCodes.push(response ? response.statusCode : -1);
                                        drmLicenseMetrics.latencies.push(-1);
                                        log('Widevine license error: ' + JSON.stringify(err));
                                        pendingLicenseDataToSend = true;
                                        callback(err);
                                        return;
                                    }

                                    drmLicenseMetrics.errorCodes.push(0);
                                    drmLicenseMetrics.serverResponseCodes.push(response.statusCode);
                                    drmLicenseMetrics.latencies.push(latency);
                                    log('Widevine license acquired - latency: ' + latency + 'ms');
                                    pendingLicenseDataToSend = true;

                                    callback(null, responseBody);
                                });
                            }
                        }
                    }
                };
                contentUri = dashUri;
            } else {
                // No DRM - use clear content
                playerConfig = {
                    src: contentUri,
                    type: getVideoMimeType(contentUri)
                };
                log("No DRM - playing clear content");
            }

            if (playerConfig) {
                player.src(playerConfig);
                log('DRM configured for: ' + activeDrm.type);
            }
        });
    }

    function setupLicenseFilters() {
        // Additional license request/response tracking for PlayReady and Widevine
        // FairPlay tracking is handled directly in the getLicense callback
        if (activeDrm.type === 'PlayReady' || activeDrm.type === 'Widevine') {
            player.on('keystatuschange', function(event) {
                log('Key status changed: ' + JSON.stringify(event));
            });

            player.on('keysessioncreated', function(event) {
                drmLicenseMetrics.requestTimestamp = Date.now();
                drmLicenseMetrics.requestCount++;
                log('DRM license session created - request count: ' + drmLicenseMetrics.requestCount);
            });
        }
    }
}

function extractChallengeOnly(keyMessage) {
    try {
        if (typeof keyMessage === 'string') {
            // Remove and normalise all non-standard characters
            keyMessage = keyMessage.split('').map(char => {
                const code = char.charCodeAt(0);
                // Keep only common ASCII characters
                return (code > 31 && code < 127) ? char : '';
            }).join('');

            // Extracting the Challenge tag and content inside a PlayReadyKeyMessage
            const challengeRegex = /<PlayReadyKeyMessage.*?><LicenseAcquisition.*?><Challenge\s+encoding="base64encoded">(.*?)<\/Challenge>/s;
            const match = keyMessage.match(challengeRegex);
            
            if (match && match[1]) {
                return match[1];
            }

            console.warn('Challenge content not found');
            return keyMessage;
        } else {
            const keyMessageString = String.fromCharCode.apply(null, new Uint8Array(keyMessage));
            return extractChallengeOnly(keyMessageString);
        }
    } catch (error) {
        console.error('Error extracting Challenge:', error);
        return keyMessage;
    }
}

function getBrowserType() {
    const userAgent = navigator.userAgent.toLowerCase();
    if (userAgent.includes('edge') || userAgent.includes('edg')) {
        return 'edge';
    } else if (userAgent.includes('chrome')) {
        return 'chrome';
    } else if (userAgent.includes('firefox')) {
        return 'firefox';
    } else if (userAgent.includes('safari') && !userAgent.includes('chrome')) {
        return 'safari';
    } else if (userAgent.includes('opera') || userAgent.includes('opr')) {
        return 'opera';
    } else {
        return 'unknown';
    }
}

function getDrmAuthData() {
    if (activeDrm.type === 'Widevine') {
        return widevineToken;
    } else if (activeDrm.type === 'PlayReady') {
        return playreadyToken;
    } else if (activeDrm.type === 'FairPlay') {
        return fairplayToken;
    } else {
        return 'no-drm';
    }
}

function getVideoMimeType(url) {
    const extension = url.split('.').pop().toLowerCase();
    switch (extension) {
        case 'mp4':
            return 'video/mp4';
        case 'm3u8':
            return 'application/x-mpegURL';
        case 'mpd':
            return 'application/dash+xml';
        case 'webm':
            return 'video/webm';
        default:
            return 'video/mp4';
    }
}

// Enhanced CMCD data handler for VideoJS
function handleCmcdDataGenerated(cmcdData) {
    log('CMCD v2 Event Mode data generated:');

    // Parse and display CMCD data
    let data = {};
    if (typeof cmcdData === 'string') {
        // Parse query string format
        const pairs = cmcdData.split(',');
        pairs.forEach(function(pair) {
            const keyValue = pair.split('=');
            if (keyValue.length === 2) {
                let key = keyValue[0];
                let value = keyValue[1];

                // Remove quotes from string values
                if (value.startsWith('"') && value.endsWith('"')) {
                    value = value.slice(1, -1);
                }

                // Convert numbers
                if (!isNaN(value) && value.trim() !== '') {
                    value = Number(value);
                }

                data[key] = value;
            }
        });
    } else {
        data = cmcdData;
    }

    // Sort and log keys
    const keys = Object.keys(data).sort();
    keys.forEach(function(key) {
        log('  ' + key.padEnd(8) + ': ' + data[key]);
    });

    log('');
}

// Initialize when DOM is ready
document.addEventListener('DOMContentLoaded', function() {
    init();
});